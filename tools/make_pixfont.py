#!/usr/bin/env python3
"""Pre-render Silkscreen into sprite sheets for apps/wefunk (the unit's font engine,
patched for DynaComware's FDL fonts, loads TrueType files but draws no glyphs).

    .venv/bin/python tools/make_pixfont.py

Writes apps/wefunk/font/SIZE-COLOR-SHADOW.png (16 glyphs per row, ASCII 32-126, the
web player's 2 px drop shadow baked in) and apps/wefunk/font.js (advances and sheet
positions; PixText.qml lays text out with it). Re-run after changing COLORS/SHADOWS.
"""
import json
import os
import sys

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
from PySide6.QtCore import QPoint  # noqa: E402
from PySide6.QtGui import QColor, QFont, QFontDatabase, QFontMetrics, QGuiApplication, QImage, QPainter  # noqa: E402

PROJECT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP = os.path.join(PROJECT, "apps", "wefunk")
TTF = os.path.join(APP, "Silkscreen.ttf")
SIZES = (16, 24)
COLORS = ("dcdcec", "d8cc2c", "9c9cdc", "e4e9f7", "eaeffd")   # text, yellow, dim, button, title
SHADOWS = ("0a0a4e", "34343e", "30303a")                      # body, button, title bar
SHADOW = 2
SPACING = 1      # CSS letter-spacing: 1px
COLS = 16
FIRST, LAST = 32, 126


def main():
    app = QGuiApplication(sys.argv)  # noqa: F841 (fonts need a GUI application)
    fid = QFontDatabase.addApplicationFont(TTF)
    if fid < 0:
        sys.exit("cannot load %s" % TTF)
    family = QFontDatabase.applicationFontFamilies(fid)[0]
    os.makedirs(os.path.join(APP, "font"), exist_ok=True)
    metrics = {}
    for size in SIZES:
        font = QFont(family)
        font.setPixelSize(size)
        font.setStyleStrategy(QFont.NoAntialias)
        fm = QFontMetrics(font)
        adv = [fm.horizontalAdvance(chr(c)) + SPACING for c in range(FIRST, LAST + 1)]
        cell_w = max(adv) + SHADOW
        cell_h = fm.ascent() + fm.descent() + SHADOW
        rows = (LAST - FIRST + COLS) // COLS
        metrics[str(size)] = {"adv": adv, "cw": cell_w, "ch": cell_h, "cols": COLS}
        for color in COLORS:
            for shadow in SHADOWS:
                img = QImage(COLS * cell_w, rows * cell_h, QImage.Format_ARGB32)
                img.fill(0)
                p = QPainter(img)
                p.setRenderHint(QPainter.TextAntialiasing, False)
                p.setFont(font)
                for i, c in enumerate(range(FIRST, LAST + 1)):
                    x, y = (i % COLS) * cell_w, (i // COLS) * cell_h + fm.ascent()
                    p.setPen(QColor("#" + shadow))
                    p.drawText(QPoint(x + SHADOW, y + SHADOW), chr(c))
                    p.setPen(QColor("#" + color))
                    p.drawText(QPoint(x, y), chr(c))
                p.end()
                img.save(os.path.join(APP, "font", "%d-%s-%s.png" % (size, color, shadow)))
    with open(os.path.join(APP, "font.js"), "w") as fh:
        fh.write("// generated by tools/make_pixfont.py: Silkscreen metrics for PixText.qml\n")
        fh.write(".pragma library\n\n")
        fh.write("var FIRST = %d, LAST = %d, SHADOW = %d;\n" % (FIRST, LAST, SHADOW))
        fh.write("var M = %s;\n\n" % json.dumps(metrics, separators=(",", ":")))
        fh.write(LAYOUT_JS)
    print("wrote %d sheets and font.js" % (len(SIZES) * len(COLORS) * len(SHADOWS)))


LAYOUT_JS = r"""
/* characters outside ASCII, after upper-casing */
var MAP = {"—": "-", "–": "-", "’": "'", "‘": "'", "“": "\"", "”": "\"",
    "…": "...", "À": "A", "Á": "A", "Â": "A", "Ã": "A", "Ä": "A", "Å": "A",
    "Æ": "AE", "Ç": "C", "È": "E", "É": "E", "Ê": "E", "Ë": "E", "Ì": "I",
    "Í": "I", "Î": "I", "Ï": "I", "Ñ": "N", "Ò": "O", "Ó": "O", "Ô": "O",
    "Õ": "O", "Ö": "O", "Ø": "O", "Ù": "U", "Ú": "U", "Û": "U", "Ü": "U",
    "Ý": "Y", "ß": "SS", " ": " "};

function clean(text) {
    var s = String(text).toUpperCase(), out = "";
    for (var i = 0; i < s.length; i++) {
        var c = s.charAt(i), code = s.charCodeAt(i);
        if (code >= FIRST && code <= LAST)
            out += c;
        else if (MAP[c] !== undefined)
            out += MAP[c];
        else if (c === "\n" || c === "\t")
            out += " ";
        else
            out += "?";
    }
    return out;
}

function width(s, m) {
    var w = 0;
    for (var i = 0; i < s.length; i++)
        w += m.adv[s.charCodeAt(i) - FIRST];
    return w;
}

function fit(s, m, box) {          /* cut s to box px, ending in "..." */
    if (box <= 0 || width(s, m) <= box)
        return s;
    while (s.length && width(s, m) + width("...", m) > box)
        s = s.substring(0, s.length - 1);
    return s.replace(/\s+$/, "") + "...";
}

/* -> {g: [[sheetX, sheetY, cellW, x, y], ...], w, h, ch} */
function layout(text, size, box, elide, wrap, maxLines, align) {
    var m = M[String(size)] || M["16"];
    var s = clean(text), lines = [];
    if (wrap && box > 0) {
        var words = s.split(" "), line = "";
        for (var i = 0; i < words.length; i++) {
            var next = line === "" ? words[i] : line + " " + words[i];
            if (line !== "" && width(next, m) > box) {
                lines.push(line);
                line = words[i];
            } else {
                line = next;
            }
        }
        lines.push(line);
        if (maxLines > 0 && lines.length > maxLines) {
            lines = lines.slice(0, maxLines);
            lines[maxLines - 1] = fit(lines[maxLines - 1] + " " + "\u0000", m, box).replace("\u0000", "");
            if (lines[maxLines - 1].slice(-3) !== "...")
                lines[maxLines - 1] = fit(lines[maxLines - 1] + "...", m, box);
        }
    } else {
        lines = [elide ? fit(s, m, box) : s];
    }
    var g = [], wmax = 0, lh = m.ch - SHADOW;
    for (var l = 0; l < lines.length; l++)
        wmax = Math.max(wmax, width(lines[l], m));
    var area = box > 0 ? box : wmax;
    for (l = 0; l < lines.length; l++) {
        var lw = width(lines[l], m);
        var x = align === "center" ? Math.floor((area - lw) / 2) : align === "right" ? area - lw : 0;
        for (var j = 0; j < lines[l].length; j++) {
            var k = lines[l].charCodeAt(j) - FIRST;
            if (k > 0)      /* spaces need no glyph */
                g.push([(k % m.cols) * m.cw, Math.floor(k / m.cols) * m.ch, m.adv[k] + SHADOW, x, l * (lh + 4)]);
            x += m.adv[k];
        }
    }
    return {g: g, w: wmax + SHADOW, h: lines.length * (lh + 4) - 4 + SHADOW, ch: m.ch};
}
"""

if __name__ == "__main__":
    main()
